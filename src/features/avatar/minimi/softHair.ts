import type { PixelPen } from "./details";
import type { PixelPalette } from "./wardrobe";

type Point = readonly [number, number];
const blend = (a: string, b: string, amount: number) =>
  "#" +
  [1, 3, 5]
    .map((i) =>
      Math.round(
        parseInt(a.slice(i, i + 2), 16) * (1 - amount) +
          parseInt(b.slice(i, i + 2), 16) * amount,
      )
        .toString(16)
        .padStart(2, "0"),
    )
    .join("");

