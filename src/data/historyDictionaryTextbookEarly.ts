// Definitions are newly written learning summaries, not reproduced textbook text.
// The same lessons occur at different PDF offsets in the complete/semester books.
const review = (
  word: string,
  definition: string,
  printedPages: number | number[],
  eras: string | string[],
  topics: string | string[],
  aliases: string[] = [],
  place?: { matchId: string; region: string },
): HistoryDictionaryTextbookReview => ({
  word,
  definition,
  aliases,
  facetIds: [
    "subject:korea",
    ...(Array.isArray(eras) ? eras : [eras]).map((era) => `era:${era}`),
    ...(place ? [`region:${place.region}`] : []),
    ...(Array.isArray(topics) ? topics : [topics]).map(
      (topic) => `topic:${topic}`,
    ),
  ],
  ...(place ? { matchId: place.matchId, kind: "place" as const } : {}),
  sources: (Array.isArray(printedPages)
    ? printedPages
    : [printedPages]
  ).flatMap((printedPage) => [
    { book: "history2" as const, pdfPage: printedPage - 2, printedPage },
    ...(printedPage <= 111
      ? [
          {
            book: "history2-sem1" as const,
            pdfPage: printedPage - 4,
            printedPage,
          },
        ]
      : []),
  ]),
});

