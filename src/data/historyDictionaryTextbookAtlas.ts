const history = (
  pdfPage: number,
  word: string,
  definition: string,
  era: string,
  topic: string,
  aliases: string[] = [],
): HistoryDictionaryTextbookReview => {
  const matched = existingAtlasEntries[word];
  return {
    word,
    definition,
    aliases,
    kind: matched ? "place" : "history",
    ...(matched ? { matchId: matched.matchId } : {}),
    facetIds: [
      "subject:world",
      `era:${era}`,
      `topic:${topic}`,
      ...(matched?.regions.map((region) => `region:${region}`) || []),
    ],
    sources: source(pdfPage),
  };
};
const place = (
  pdfPage: number,
  word: string,
  definition: string,
  era: string,
  region: string | string[],
  topic: string,
  matchId?: string,
  aliases: string[] = [],
): HistoryDictionaryTextbookReview => ({
  word,
  definition,
  aliases,
  kind: "place",
  ...(matchId ? { matchId } : {}),
  facetIds: [
    era.startsWith("k-") ? "subject:korea" : "subject:world",
    `era:${era}`,
    ...(Array.isArray(region) ? region : [region]).map((id) => `region:${id}`),
    `topic:${topic}`,
  ],
  sources: source(pdfPage),
});

