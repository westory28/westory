// Foldouts contain two printed pages in one PDF page. Both page numbers are retained.
const source = (
  pdfPage: number,
): HistoryDictionaryTextbookReview["sources"] => {
  const foldouts: Record<number, number[]> = {
    17: [17, 18],
    19: [20, 21],
    65: [67, 68],
    66: [69, 70],
  };
  const pages = foldouts[pdfPage] || [
    pdfPage + (pdfPage >= 67 ? 4 : pdfPage >= 20 ? 2 : pdfPage === 18 ? 1 : 0),
  ];
  return pages.map((printedPage) => ({ book: "atlas", pdfPage, printedPage }));
};
