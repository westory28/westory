import fs from 'node:fs/promises';
import path from 'node:path';
import ts from 'typescript';

// Ship the exact game chart and judgement rules to the server. --check catches
// a client scoring update that forgot to refresh the trusted replay implementation.
const check = process.argv.includes('--check');
for (const name of ['rhythmCore', 'rhythmSongs']) {
  const source = await fs.readFile(`src/components/common/weplay/rhythm/${name}.ts`, 'utf8');
  const code = '// Generated by scripts/generate-rhythm-ranking-core.mjs. Do not edit.\n' +
    ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS } }).outputText;
  const target = path.join('functions', 'rhythmRankingCore', `${name}.js`);
  if (check) {
    if ((await fs.readFile(target, 'utf8')).replace(/\r\n/g, '\n') !== code.replace(/\r\n/g, '\n')) throw new Error(`Stale rhythm replay: ${target}`);
  } else {
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, code);
  }
}
console.log('Rhythm ranking replay matches the game chart and scoring.');
