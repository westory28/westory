for (const character of ["girl", "boy"]) {
  const art = spec.characters[character];
  art.groups = {
    head: { pivot: [0.5, 0.38] },
    hair: { parent: "head", pivot: [0.5, 0.38] },
    face: { parent: "head", pivot: [0.5, 0.38] },
  };
  art.base = ["leg", { ref: "leg", id: "right-leg", mirror: true }];
  art.poses = Object.fromEntries(
    ["idle", "wave", "cheer", "think", "heart"].map((p) => [p, {}]),
  );
  art.poses.tilt = { transforms: { head: { rotation: -0.1 } } };
  art.slots.top = {};
  for (const item of catalog.filter((i) => i.slot === "top")) {
    const f = family(item.value);
    const layerFor = (pose) => {
      const id = `v3-${item.value}-${pose}`;
      if (!spec.variants.some((v) => v.id === id))
        spec.variants.push({
          id,
          ref: topCells[f][pose],
          recolor: {
            color: item.color,
            sourceColor: sourceColors[f],
            mode: ["plain", "polo"].includes(f) ? "neutral" : "chroma",
            excludeSkin: true,
          },
        });
      return [{ ref: id, id: "outfit", z: 30 }];
    };
    art.slots.top[item.value] = {
      layers: layerFor("idle"),
      ...(f === "robe" ? { hideSlots: ["bottom"] } : {}),
      poses: Object.fromEntries(
        poses
          .filter((p) => p !== "idle")
          .map((p) => [p, { layers: layerFor(p) }]),
      ),
    };
  }
  art.slots.bottom = {};
  for (const item of catalog.filter(
    (i) => i.slot === "bottom" && i.characters.includes(character),
  )) {
    const f = item.value.startsWith("pleated")
      ? "pleated"
      : item.value.startsWith("chima")
        ? "chima"
        : item.value.startsWith("baji")
          ? "baji"
          : item.value === "summer-shorts"
            ? "shorts"
            : "trousers";
    const id = `v3-${item.value}`;
    if (!spec.variants.some((v) => v.id === id))
      spec.variants.push({
        id,
        ref: `v3-${f}`,
        recolor: {
          color: item.color,
          sourceColor: lowerFamilies[f].source,
          mode: f === "trousers" ? "neutral" : "chroma",
        },
      });
    art.slots.bottom[item.value] = {
      layers: [id],
      ...(f === "trousers" ? { hideIds: ["leg", "right-leg"] } : {}),
    };
  }
  art.slots.shoes = Object.fromEntries(
    shoeItems.map((item) => [item.value, [`v3-${item.value}`]]),
  );
  for (const [name, selection] of Object.entries(art.slots.hairStyle)) {
    const entries = Array.isArray(selection) ? selection : selection.layers;
    const original = entries[0];
    const ref = typeof original === "string" ? original : original.ref;
    art.slots.hairStyle[name] = [
      { ref, id: "hair-back", z: 5, group: "hair", clip: [0, 0.376, 1, 0.624] },
      { ref, id: "hair-front", z: 50, group: "hair", clip: [0, 0, 1, 0.38] },
    ];
  }
  for (const [hat, y] of [
    ["official-samo", 0.155],
    ["official-gat", 0.18],
  ]) {
    const existing = art.slots.accessory[hat];
    art.slots.accessory[hat] = {
      layers: Array.isArray(existing) ? existing : existing.layers,
      clipGroups: { hair: [0, y, 1, 1 - y], face: [0, y, 1, 1 - y] },
    };
  }
}
