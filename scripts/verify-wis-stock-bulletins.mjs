  advance(1);
  assert.deepEqual([current.stocks[0].kind, current.stocks[0].id, current.stocks[0].exit], ['exit', 'merged', 'merge']);
  advance(10_000);
  assert.equal(current.stocks[0].id, '급등락', 'a closed stock produces no separate price headline');
