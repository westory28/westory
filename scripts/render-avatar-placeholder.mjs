/** Derive the placeholder from the actual idle minimi, never a separate drawing. */
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import http from "node:http";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { format } from "prettier";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const destination = path.join(
  root,
  "src/features/avatar/avatarPlaceholderImage.ts",
);
const require = createRequire(import.meta.url);
let playwright;
try {
  playwright = require("playwright");
} catch {
  playwright = require(
    process.env.PLAYWRIGHT_MODULE_PATH ||
      path.join(
        os.homedir(),
        ".cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright",
      ),
  );
}
const bundle = await build({
  stdin: {
    resolveDir: root,
    loader: "ts",
    contents: `
import {drawMinimi,MINIMI_WIDTH,MINIMI_HEIGHT} from './src/features/avatar/minimi/draw';
import {defaultAvatarLook} from './src/features/avatar/catalog';
const source = document.createElement('canvas'); source.width=MINIMI_WIDTH; source.height=MINIMI_HEIGHT;
const ctx=source.getContext('2d'); const look=defaultAvatarLook();
drawMinimi(ctx,look);
window.placeholderSource={width:MINIMI_WIDTH,height:MINIMI_HEIGHT,look,
  alpha:Array.from(ctx.getImageData(0,0,MINIMI_WIDTH,MINIMI_HEIGHT).data).filter((_,i)=>i%4===3)};
window.verifyPlaceholder=async svg=>{
  const image=new Image(); image.src='data:image/svg+xml,'+encodeURIComponent(svg); await image.decode();
  ctx.clearRect(0,0,source.width,source.height);ctx.drawImage(image,0,0);
  const data=ctx.getImageData(0,0,source.width,source.height).data;
  return {alpha:Array.from(data).filter((_,i)=>i%4===3),
    colors:[...new Set(Array.from({length:data.length/4},(_,i)=>data[i*4+3] ? Array.from(data.slice(i*4,i*4+3)).join(',') : '').filter(Boolean))]};
};`,
  },
  bundle: true,
  write: false,
  platform: "browser",
  format: "esm",
});
const server = http.createServer((request, response) =>
  request.url === "/source.js"
    ? response
        .writeHead(200, { "Content-Type": "text/javascript" })
        .end(bundle.outputFiles[0].contents)
    : response
        .writeHead(200, { "Content-Type": "text/html" })
        .end('<!doctype html><script type="module" src="/source.js"></script>'),
);
await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
const browser = await playwright.chromium.launch({
  headless: true,
  channel:
    process.env.PLAYWRIGHT_BROWSER_CHANNEL ||
    (process.platform === "win32" ? "msedge" : undefined),
});
try {
  const page = await browser.newPage();
  await page.route("**/*", (route) =>
    route.request().url().startsWith(origin) ? route.continue() : route.abort(),
  );
  await page.goto(origin);
  await page.waitForFunction(() => window.placeholderSource);
  const { width, height, alpha, look } = await page.evaluate(
    () => window.placeholderSource,
  );
  assert.equal(look.pose, "mm-idle");
  assert(
    alpha.every((value) => value === 0 || value === 255),
    "Renderer uses integer opaque pixels",
  );
  // Merge equal horizontal runs on adjacent rows into rectangles. Geometry is
  // copied from occupied renderer pixels; no hand-authored character coordinates.
  const rectangles = [];
  let previous = new Map();
  for (let y = 0; y < height; y++) {
    const current = new Map();
    for (let x = 0; x < width; ) {
      if (!alpha[y * width + x]) {
        x++;
        continue;
      }
      const start = x;
      while (x < width && alpha[y * width + x]) x++;
      const key = `${start}:${x - start}`;
      const rectangle = previous.get(key) || {
        x: start,
        y,
        width: x - start,
        height: 0,
      };
      if (!previous.has(key)) rectangles.push(rectangle);
      rectangle.height++;
      current.set(key, rectangle);
    }
    previous = current;
  }
  const geometry = rectangles
    .map(
      (rect) =>
        `M${rect.x} ${rect.y}h${rect.width}v${rect.height}h-${rect.width}z`,
    )
    .join("");
  const svg =
    `<!-- Generated by scripts/render-avatar-placeholder.mjs from drawMinimi(defaultAvatarLook()). -->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" shape-rendering="crispEdges"><path fill="#cbd5e1" d="${geometry}"/></svg>\n`;
  const checked = await page.evaluate(
    (svg) => window.verifyPlaceholder(svg),
    svg,
  );
  assert.deepEqual(
    checked.alpha,
    alpha,
    "Static silhouette must preserve every renderer alpha pixel",
  );
  assert.deepEqual(
    checked.colors,
    ["203,213,225"],
    "Single existing neutral color",
  );
  const module = await format(
    `// Generated by scripts/render-avatar-placeholder.mjs; exact drawMinimi(defaultAvatarLook()) alpha.\n` +
      `const silhouette = ${JSON.stringify(svg)};\n\n` +
      `export default "data:image/svg+xml," + encodeURIComponent(silhouette);\n`,
    { parser: "typescript" },
  );
  if (process.argv.includes("--check"))
    assert.equal(
      (await fs.readFile(destination, "utf8")).replaceAll("\r\n", "\n"),
      module,
      "Regenerate the placeholder after the default character shape changes",
    );
  else await fs.writeFile(destination, module);
  console.log(
    JSON.stringify({
      passed: true,
      mode: process.argv.includes("--check") ? "check" : "generate",
      width,
      height,
      opaquePixels: alpha.filter(Boolean).length,
      rectangles: rectangles.length,
      bytes: Buffer.byteLength(svg),
      exactRendererAlpha: true,
      externalRequests: 0,
    }),
  );
} finally {
  await browser.close();
  await new Promise((resolve) => server.close(resolve));
}
